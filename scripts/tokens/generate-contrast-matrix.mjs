/**
 * tokens/generate-contrast-matrix — regenerates docs/CONTRAST-MATRIX.md from
 * `@autopilot/tokens`' own `contrastMatrix()` (epic 0015 §6.6, board
 * web-mtd1wmrg-9w5bk7: "generate the fg x bg pass/fail matrix per theme (3
 * themes) as a committed artifact"). `packages/tokens/test/contrast-matrix.test.ts`
 * gates the DATA (no pair may regress below 3:1 versus today's baseline); this
 * script gates the DOC that makes that data human-readable, the piece the prior
 * firing's "complete" claim was demoted for shipping without ("the patch touches
 * no UI/Docs surface") — the test alone is invisible to anyone who is not
 * reading `packages/tokens/test/`.
 *
 * `--check` compares the freshly rendered doc against what's committed and
 * fails without writing if it differs (the `ci:contrast-matrix` gate, wired
 * into `pnpm verify`); with no flag it writes the refreshed doc in place
 * (`pnpm contrast-matrix:update`). Every value here is a pure function of the
 * theme token maps — no clock, no environment — so unlike `data-model:update`'s
 * generated-timestamp line, this doc has nothing non-deterministic to strip
 * before comparing.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { THEME_NAMES, THEMES, contrastMatrix } from '../../packages/tokens/dist/index.js';

const repoRoot = fileURLToPath(new URL('../..', import.meta.url));
const DOC_PATH = join(repoRoot, 'docs', 'CONTRAST-MATRIX.md');

const LEVEL_LABEL = {
  fail: 'fail (< 3:1)',
  large: 'large text / non-text only (3:1–4.5:1)',
  text: 'normal text ready (≥ 4.5:1)',
};

function renderPairTable(pairs) {
  const lines = ['| pair | ratio |', '| --- | --- |'];
  for (const pair of pairs) {
    lines.push(`| \`${pair.a}\` on \`${pair.b}\` | ${pair.ratio.toFixed(2)} |`);
  }
  return lines.join('\n');
}

function renderLevelGroup(level, pairs, collapse) {
  const matching = pairs.filter((pair) => pair.level === level).sort((a, b) => a.ratio - b.ratio);
  const heading = `**${LEVEL_LABEL[level]}** — ${matching.length} of ${pairs.length} pairs`;
  if (matching.length === 0) return `${heading}. _None._`;
  const table = renderPairTable(matching);
  if (!collapse) return `${heading}\n\n${table}`;
  return [`<details><summary>${heading}</summary>`, '', table, '', '</details>'].join('\n');
}

function renderTheme(name) {
  const pairs = contrastMatrix(THEMES[name]);
  return [
    `### ${name}`,
    '',
    renderLevelGroup('fail', pairs, false),
    '',
    renderLevelGroup('large', pairs, false),
    '',
    renderLevelGroup('text', pairs, true),
  ].join('\n');
}

function renderDoc() {
  const sections = [
    '<!--',
    // REUSE-IgnoreStart
    'SPDX-FileCopyrightText: 2026 1337 · REL AZEUS · MΔSTERMIND',
    'SPDX-License-Identifier: Apache-2.0',
    // REUSE-IgnoreEnd
    '-->',
    '',
    '# AUTOPILOT contrast matrix',
    '',
    "_Generated by `pnpm contrast-matrix:update` from `@autopilot/tokens`'s" +
      ' `contrastMatrix()` — the same OKLCH→WCAG-contrast core' +
      ' `packages/tokens/test/themes.test.ts` and' +
      ' `packages/tokens/test/contrast-matrix.test.ts` enforce ratios with —' +
      ' over every unordered pair of the 18 semantic color tokens' +
      ' (`COLOR_TOKENS`), per theme. Not every pair below is ever actually' +
      ' rendered together; this is the reference ledger the epic 0015 §6.6' +
      ' design-system recon (token double-duty audit) reads, not a claim that' +
      ' all 153 combinations occur in the served CSS._',
    '',
    'Floors: **4.5:1** normal text (WCAG 1.4.3), **3:1** large text and' +
      ' non-text UI components (1.4.11 — borders, chip fills, icons). Run' +
      ' `pnpm contrast-matrix:update` after a theme token edit;' +
      ' `pnpm run verify` fails (`ci:contrast-matrix`) if this file is stale,' +
      ' and `contrast-matrix.test.ts` separately fails if a previously-passing' +
      ' pair regresses below 3:1 — this doc is the human-readable mirror of' +
      ' that gate, not a second source of truth for it.',
    '',
    THEME_NAMES.map((name) => renderTheme(name)).join('\n\n'),
    '',
  ];
  return sections.join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  const next = renderDoc();

  if (check) {
    const source = (() => {
      try {
        return readFileSync(DOC_PATH, 'utf8');
      } catch {
        return '';
      }
    })();
    if (next !== source) {
      console.error(
        'contrast-matrix-check FAILED: docs/CONTRAST-MATRIX.md is stale — run' +
          ' `pnpm contrast-matrix:update` and commit the result.',
      );
      process.exit(1);
    }
    console.log('contrast-matrix-check OK: docs/CONTRAST-MATRIX.md matches the token themes.');
    return;
  }

  writeFileSync(DOC_PATH, next);
  console.log(
    `generate-contrast-matrix: docs/CONTRAST-MATRIX.md refreshed (${THEME_NAMES.length} themes).`,
  );
}

try {
  main();
} catch (err) {
  console.error(
    `generate-contrast-matrix FAILED: ${err instanceof Error ? err.message : String(err)}`,
  );
  process.exit(1);
}
