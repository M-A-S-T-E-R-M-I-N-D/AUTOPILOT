/**
 * App-wide interactivity audit: the task board's "Add" submit button (the
 * human side of the board, `[data-task-add] button`) was the last silent
 * control on the panel — every reorder/focus/approve/reject/done/delete
 * button next to it already explained itself via the shared [data-tip]
 * primitive, but this one carried neither data-tip nor aria-label.
 */

import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest';
import { renderShell, clientJs } from '../../src/web/shell.js';

const PROJECT = {
  id: 'p1',
  slug: 'alpha',
  name: 'Alpha',
  status: 'idle',
  createdAt: 1,
  primaryLanguage: 'typescript',
  fileCount: 12,
  totalBytes: 4096,
  languages: [],
  topDirs: [],
  hotFiles: [],
  gate: null,
  backedUp: false,
  firings: 0,
  shipped: 0,
  cost: 0,
  tokensIn: 0,
  tokensOut: 0,
  shipRate: null,
  openFindings: 0,
  gauge: { critical: 0, high: 0, medium: 0, low: 0 },
  lastActivityAt: 1,
  activity: [],
  flightLog: [],
  tasks: [],
};

const STATE = {
  generatedAt: 1,
  totals: {
    projects: 1,
    flying: 0,
    needsYou: 0,
    firings: 0,
    shipped: 0,
    openFindings: 0,
    cost: 0,
  },
  projects: [PROJECT],
  empty: false,
};

function boot(projectId: string): void {
  document.open();
  document.write(renderShell(projectId));
  document.close();
  globalThis.fetch = vi.fn(
    async () => ({ ok: true, json: async () => STATE }) as unknown as Response,
  );
  new Function(clientJs())();
}

describe('task-add "Add" button explains itself on hover/focus', () => {
  beforeEach(() => vi.useFakeTimers());
  afterEach(() => {
    vi.useRealTimers();
    vi.restoreAllMocks();
  });

  it('carries a data-tip matching its aria-label', async () => {
    boot('p1');
    await vi.advanceTimersByTimeAsync(1);

    const btn = document.querySelector('[data-task-add] button');
    expect(btn).toBeTruthy();
    const tip = btn?.getAttribute('data-tip');
    expect(tip).toBeTruthy();
    expect(tip).toBe('Queue a new operator task for the autopilot to pick up');
    expect(tip).toBe(btn?.getAttribute('aria-label'));
  });
});
